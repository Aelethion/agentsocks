import { WAKE_PREFIX } from "../../codexframe.ts";
import { VERSION } from "../../version.ts";

export const PLUGIN_NAME = "agentsocks";
export const PLUGIN_MARKER = "# agentsocks:managed hermes-plugin";
export const PLUGIN_FILES = ["plugin.yaml", "__init__.py"] as const;
export type PluginFile = (typeof PLUGIN_FILES)[number];
export const PLUGIN_HOOKS = ["on_session_start", "on_session_open", "on_session_end", "pre_llm_call"] as const;

export interface PluginSpec {
  node: string;
  cli: string;
  pinned: [string, string][];
}

// A JSON string is a valid Python string literal once the separators Python reads as line ends are escaped.
const py = (value: string): string => JSON.stringify(value).replace(/[\u0085\u2028\u2029]/g, (c) => `\\u${c.charCodeAt(0).toString(16).padStart(4, "0")}`);

const header = `${PLUGIN_MARKER} (generated by agentsocks install; edits are overwritten, and agentsocks uninstall deletes this file)`;

function manifest(): string {
  return [
    header,
    `name: ${PLUGIN_NAME}`,
    "kind: standalone",
    `version: "${VERSION}"`,
    'requires_hermes: ">=0.23.0"',
    'description: "agentsocks wake bridge: starts a turn in an idle chat when an agentsocks message arrives for it. Only content-free notice lines pass through; the message is read with the agentsocks tools."',
    "author: agentsocks",
    "provides_hooks:",
    ...PLUGIN_HOOKS.map((h) => `  - ${h}`),
    "",
  ].join("\n");
}

// The broker hands the plugin fixed notice lines and nothing a sender wrote; the plugin checks each line again
// before Hermes gets it.
function module(spec: PluginSpec): string {
  return `${header}
"""agentsocks wake bridge for Hermes.

Each chat this Hermes process hosts is attached to one sink (a random id for this process) the first time
one of its hooks fires. One background thread long-polls the agentsocks broker for wakes on that sink and
hands each notice line to ctx.inject_message for the chat it names, which starts a turn in an idle chat.
"""
import json
import logging
import os
import re
import secrets
import subprocess
import threading

NODE = ${py(spec.node)}
CLI = ${py(spec.cli)}
PINNED = {${spec.pinned.map(([k, v]) => `${py(k)}: ${py(v)}`).join(", ")}}
PREFIX = ${py(WAKE_PREFIX)}
HOOKS = (${PLUGIN_HOOKS.map(py).join(", ")},)
SESSION = re.compile(r"^[A-Za-z0-9_-]{1,72}$")
KEEP_ENV = frozenset(("PATH", "HOME", "USER", "LOGNAME", "SHELL", "LANG", "TMPDIR", "TMP", "TEMP", "XDG_RUNTIME_DIR", "XDG_STATE_HOME", "XDG_CONFIG_HOME", "XDG_DATA_HOME", "XDG_CACHE_HOME", "CLAUDE_CONFIG_DIR", "CODEX_HOME", "NODE_OPTIONS", "NODE_PATH"))
ATTACH_TIMEOUT = 4.0
POLL_MS = 25000
POLL_SLACK = 15.0
MAX_BACKOFF = 30.0
MAX_LINE = 600
MAX_OUTPUT = 1000000

logger = logging.getLogger("hermes_plugins.agentsocks")


def _env():
    env = {k: v for k, v in os.environ.items() if k in KEEP_ENV or k.startswith("AGENTSOCKS_") or k.startswith("LC_")}
    env.update(PINNED)
    env["NODE_NO_WARNINGS"] = "1"
    return env


def _parse(text):
    try:
        value = json.loads(text)
    except (TypeError, ValueError):
        return None
    return value if isinstance(value, dict) else None


class Bridge:
    def __init__(self, ctx, spawn):
        self.ctx = ctx
        self.spawn = spawn
        self.sink = "hermes-" + secrets.token_hex(8)
        self.lock = threading.Lock()
        self.claimed = set()
        self.attached = set()
        self.children = set()
        self.ready = threading.Event()
        self.stopped = threading.Event()

    def run(self, event, payload, timeout):
        """One agentsocks hook command: its stdout, or None when it failed, timed out or was stopped."""
        if self.stopped.is_set():
            return None
        try:
            child = subprocess.Popen([NODE, CLI, "hook", "hermes", event], stdin=subprocess.PIPE, stdout=subprocess.PIPE, stderr=subprocess.DEVNULL, env=_env(), close_fds=True)
        except OSError:
            return None
        with self.lock:
            self.children.add(child)
        try:
            out, _ = child.communicate(json.dumps(payload).encode("utf-8"), timeout=timeout)
            return out[:MAX_OUTPUT].decode("utf-8", "replace") if child.returncode == 0 else None
        except Exception:
            try:
                child.kill()
                child.communicate(timeout=1)
            except Exception:
                pass
            return None
        finally:
            with self.lock:
                self.children.discard(child)

    def hook(self, **kwargs):
        """Every registered hook: attach a chat the first time this process sees its id, off the turn's thread."""
        return self.touch(False, kwargs)

    def opened(self, **kwargs):
        """on_session_open: Hermes opened the chat, so attach it even if this process held it before."""
        return self.touch(True, kwargs)

    def ended(self, **kwargs):
        """on_session_end: agentsocks marks the thread ended, so forget the chat until it is attached again."""
        session = kwargs.get("session_id")
        if isinstance(session, str):
            with self.lock:
                self.claimed.discard(session)
                self.attached.discard(session)
        return None

    def touch(self, force, kwargs):
        session = kwargs.get("session_id")
        if self.stopped.is_set() or not isinstance(session, str) or not SESSION.match(session):
            return None
        with self.lock:
            if session in self.claimed and not force:
                return None
            self.claimed.add(session)
        payload = {"session": session, "sink": self.sink}
        cwd = kwargs.get("cwd")
        if isinstance(cwd, str) and cwd:
            payload["cwd"] = cwd
        try:
            self.spawn(self.attach, name="agentsocks-attach", daemon=True, args=(payload,)).start()
        except Exception:
            with self.lock:
                self.claimed.discard(session)
        return None

    def attach(self, payload):
        reply = _parse(self.run("attach", payload, ATTACH_TIMEOUT))
        with self.lock:
            if reply is not None and reply.get("attached") is True:
                if payload["session"] in self.claimed:
                    self.attached.add(payload["session"])
                self.ready.set()
            else:
                self.claimed.discard(payload["session"])

    def deliver(self, wake):
        if not isinstance(wake, dict):
            return
        session, line = wake.get("session"), wake.get("line")
        if not isinstance(session, str) or not isinstance(line, str):
            return
        with self.lock:
            ours = session in self.attached
        if not ours or len(line) > MAX_LINE or "\\n" in line or not line.startswith(PREFIX):
            return
        try:
            accepted = self.ctx.inject_message(line, session_key=session)
        except Exception:
            logger.warning("agentsocks: inject_message raised for session %s", session, exc_info=True)
            return
        if accepted is not True:
            logger.warning("agentsocks: Hermes did not start a turn for session %s (the chat is closed or unknown here, or plugins.entries.agentsocks.allow_gateway_injection is not true)", session)

    def poll(self):
        failures = 0
        while not self.stopped.is_set():
            if not self.ready.wait(1.0):
                continue
            reply = _parse(self.run("wake", {"sink": self.sink, "timeoutMs": POLL_MS}, POLL_MS / 1000.0 + POLL_SLACK))
            if self.stopped.is_set():
                return
            wakes = reply.get("wakes") if reply is not None else None
            if not isinstance(wakes, list):
                failures += 1
                self.stopped.wait(min(MAX_BACKOFF, 2.0 ** failures))
                continue
            failures = 0
            for wake in wakes:
                self.deliver(wake)

    def close(self):
        self.stopped.set()
        self.ready.set()
        with self.lock:
            children = list(self.children)
        for child in children:
            try:
                child.kill()
            except Exception:
                pass


def register(ctx):
    from agent.memory_provider import spawn_context_thread

    bridge = Bridge(ctx, spawn_context_thread)
    for name in HOOKS:
        ctx.register_hook(name, {"on_session_open": bridge.opened, "on_session_end": bridge.ended}.get(name, bridge.hook))
    ctx.on_unload(bridge.close)
    spawn_context_thread(bridge.poll, name="agentsocks-wake", daemon=True).start()
`;
}

export function pluginFiles(spec: PluginSpec): Record<PluginFile, string> {
  return { "plugin.yaml": manifest(), "__init__.py": module(spec) };
}
