import { describeFor, toolsFor, type Tool } from "../../tools/index.ts";
import { createPlugin } from "./runtime.ts";
import { zodSource } from "./zodsource.ts";

export const PLUGIN_MARKER = "// agentsocks:managed opencode-plugin";
export const PLUGIN_FILE = "agentsocks.js";

export interface PluginSpec {
  node: string;
  cli: string;
  tools?: readonly Tool[];
  toolModule?: string;
}

const indent = (text: string): string => text.replace(/\n/g, "\n    ");

export function pluginSource(spec: PluginSpec): string {
  const entries = (spec.tools ?? toolsFor("codex")).map(
    (t) => `  {\n    name: ${JSON.stringify(t.name)},\n    description: ${JSON.stringify(describeFor(t, "codex"))},\n    args: ${indent(zodSource(t.inputSchema))},\n  },`,
  );
  return [
    `${PLUGIN_MARKER} (generated by agentsocks install; edits are overwritten, and agentsocks uninstall deletes this file)`,
    `import { tool } from ${JSON.stringify(spec.toolModule ?? "@opencode-ai/plugin")};`,
    `import { spawn } from "node:child_process";`,
    `import { randomBytes } from "node:crypto";`,
    ``,
    `const NODE = ${JSON.stringify(spec.node)};`,
    `const CLI = ${JSON.stringify(spec.cli)};`,
    `const TOOLS = [\n${entries.join("\n")}\n];`,
    `const createPlugin = ${createPlugin.toString()};`,
    ``,
    `export const AgentsocksPlugin = (input) => createPlugin({ spawn, randomBytes, tool, node: NODE, cli: CLI, tools: TOOLS }, input);`,
    ``,
  ].join("\n");
}
