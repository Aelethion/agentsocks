import { describeFor, toolsFor, type Tool } from "../../tools/index.ts";
import { zodSource } from "../opencode/zodsource.ts";
import { createOmpExtension } from "./runtime.ts";

export const EXTENSION_MARKER = "// agentsocks:managed omp-extension";
export const EXTENSION_FILE = "agentsocks.ts";

const OWN_INBOX = new Set(["read_inbox", "wait_for_message"]);

export interface ExtensionSpec {
  node: string;
  cli: string;
  tools?: readonly Tool[];
}

const indent = (text: string): string => text.replace(/\n/g, "\n    ");

function params(tool: Tool): string {
  try {
    return zodSource(tool.inputSchema, "z");
  } catch (err) {
    throw new Error((err as Error).message.replace(" to OpenCode:", " to OMP:"));
  }
}

export function extensionSource(spec: ExtensionSpec): string {
  const entries = (spec.tools ?? toolsFor("codex")).map((t) =>
    [
      "  {",
      `    name: ${JSON.stringify(t.name)},`,
      `    label: ${JSON.stringify(t.title)},`,
      `    description: ${JSON.stringify(describeFor(t, "codex"))},`,
      `    readOnly: ${t.annotations?.readOnlyHint === true || OWN_INBOX.has(t.name)},`,
      `    params: (z) => (${indent(params(t))}),`,
      "  },",
    ].join("\n"),
  );
  return [
    `${EXTENSION_MARKER} (generated by agentsocks install; edits are overwritten, and agentsocks uninstall deletes this file)`,
    `import { spawn } from "node:child_process";`,
    `import { randomBytes } from "node:crypto";`,
    ``,
    `const NODE = ${JSON.stringify(spec.node)};`,
    `const CLI = ${JSON.stringify(spec.cli)};`,
    `const TOOLS = [\n${entries.join("\n")}\n];`,
    `const createExtension = ${createOmpExtension.toString()};`,
    ``,
    `export default function agentsocks(pi) {`,
    `  createExtension({ spawn, randomBytes, node: NODE, cli: CLI, tools: TOOLS }, pi);`,
    `}`,
    ``,
  ].join("\n");
}
