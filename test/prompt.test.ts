import { test } from "node:test";
import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { appendFileSync, mkdirSync, rmSync, symlinkSync, utimesSync, writeFileSync, statSync } from "node:fs";
import { dirname, join } from "node:path";
import { root } from "./support.ts";
import { latestUserPrompt, openRegularFile, realUserPrompt, TranscriptWatcher } from "../src/transcript.ts";
import { GITHUB_PAT } from "./fakes.ts";

const line = (o: unknown) => `${JSON.stringify(o)}\n`;
const user = (content: unknown, extra: Record<string, unknown> = {}) => line({ type: "user", message: { role: "user", content }, ...extra });
const assistant = (text: string) => line({ type: "assistant", message: { role: "assistant", content: [{ type: "text", text }] } });

test("the latest typed prompt wins, whatever came before it and after it", () => {
  const tail = user("first task") + assistant("on it") + user([{ type: "text", text: "second task: fix the flaky checkout test" }]) + assistant("done") + line({ type: "system", subtype: "compact" });
  assert.equal(latestUserPrompt(tail), "second task: fix the flaky checkout test");
  assert.equal(latestUserPrompt(user("one") + user("two")), "two");
  assert.equal(latestUserPrompt(assistant("nothing typed here")), undefined);
  assert.equal(latestUserPrompt(""), undefined);
});

test("meta lines, tool results, peer messages, command wrappers, sidechains and system reminders are not the user's prompt", () => {
  const real = user("rewrite the parser to stream");
  const notPrompts = [
    user("a meta line whose text looks like a normal prompt", { isMeta: true }),
    user("This session is being continued from a previous conversation that ran out of context.", { isCompactSummary: true }),
    user("This session is being continued from a previous conversation that ran out of context."),
    user("<bash-input>ls -la</bash-input>"),
    user("<bash-stdout>total 0</bash-stdout>"),
    user("<user-prompt-submit-hook>blocked</user-prompt-submit-hook>"),
    user("Caveat: The messages below were generated by the user while running local commands. DO NOT respond to these messages", { isMeta: true }),
    user("<local-command-caveat>Caveat: ...</local-command-caveat>"),
    user("<command-name>/clear</command-name>\n<command-message>clear</command-message>\n<command-args></command-args>"),
    user("<local-command-stdout>done</local-command-stdout>"),
    user("Caveat: The messages below were generated by the user while running local commands."),
    user("[Request interrupted by user]"),
    user([{ type: "tool_result", tool_use_id: "t1", content: "a very long tool output" }]),
    user([{ type: "text", text: "text next to a result" }, { type: "tool_result", tool_use_id: "t2", content: "x" }]),
    user("<cross-session-message>from @codex-api: urgent</cross-session-message>"),
    user("a peer wrote this", { origin: { kind: "peer", from: "uds:/x", msg_id: "m1" } }),
    user("a subagent prompt", { isSidechain: true }),
    user("<task-notification>build finished</task-notification>"),
    user("<system-reminder>todo list reminder</system-reminder>"),
    user([{ type: "image", source: {} }]),
    user(""),
  ];
  for (const noise of notPrompts) assert.equal(latestUserPrompt(real + noise), "rewrite the parser to stream", noise.slice(0, 60));
  assert.equal(latestUserPrompt(notPrompts.join("")), undefined, "with only noise there is no prompt");
});

test("text blocks are joined, reminders inside a prompt are dropped, and whitespace is squashed", () => {
  assert.equal(realUserPrompt(JSON.parse(user([{ type: "text", text: "<system-reminder>ignore me</system-reminder>" }, { type: "text", text: "add retry\n\n   with backoff" }, { type: "image", source: {} }]))), "add retry\n\n   with backoff");
  assert.equal(latestUserPrompt(user([{ type: "text", text: "add retry\n\n   with backoff" }, { type: "text", text: "and tests" }])), "add retry with backoff and tests");
  assert.equal(latestUserPrompt(user("do this <system-reminder>noise</system-reminder> now")), "do this now");
  assert.equal(latestUserPrompt("not json at all\n" + user("real one") + "{ truncated"), "real one");
});

test("the prompt is redacted before it is cut to 200 characters, so a secret across the cut does not leak a piece", () => {
  const secret = GITHUB_PAT;
  const out = latestUserPrompt(user(`${"x".repeat(190)} ${secret} and password=hunter2 then more words`))!;
  assert.ok(!out.includes("ghp_"), out);
  assert.ok(!out.includes("hunter2"), out);
  assert.ok(out.length <= 200);
  assert.match(latestUserPrompt(user("deploy with token=abc123def and password=hunter2 please"))!, /^deploy with token=\[redacted\] and password=\[redacted\] please$/);
  assert.equal(latestUserPrompt(user("y".repeat(500)))!.length, 200);
});

function transcript(name: string, body = ""): { watcher: TranscriptWatcher; path: string; id: string } {
  const id = `${name}-${Math.random().toString(16).slice(2, 8)}`;
  const dir = join(process.env.AGENTSOCKS_CLAUDE_PROJECTS_DIR ?? join(root, "claude-projects"), `-work-${name}`);
  mkdirSync(dir, { recursive: true });
  const path = join(dir, `${id}.jsonl`);
  writeFileSync(path, body);
  return { watcher: new TranscriptWatcher(), path, id };
}

test("a huge line with an unclosed reminder tag costs linear time", () => {
  const started = Date.now();
  assert.equal(latestUserPrompt(user(`real one`) + user("<system-reminder>".repeat(14_000))), "real one");
  assert.ok(Date.now() - started < 300, `took ${Date.now() - started} ms`);
});

test("a transcript is read back in 256 KiB chunks, up to 2 MiB, until a real prompt turns up", async () => {
  const early = user("an old prompt far above the first chunk");
  const result = (kib: number) => line({ type: "user", message: { role: "user", content: [{ type: "tool_result", tool_use_id: "t", content: "z".repeat(kib * 1024) }] } });
  const near = transcript("tail-near", early + result(300));
  assert.equal(await near.watcher.latestPrompt(near.id), "an old prompt far above the first chunk", "one chunk back is not enough, two are");
  const far = transcript("tail-far", early + result(1800));
  assert.equal(await far.watcher.latestPrompt(far.id), "an old prompt far above the first chunk", "still inside 2 MiB");
  const beyond = transcript("tail-beyond", early + result(2200));
  assert.equal(await beyond.watcher.latestPrompt(beyond.id), undefined, "past 2 MiB there is no prompt");
  appendFileSync(beyond.path, user("the current task near the end"));
  assert.equal(await beyond.watcher.latestPrompt(beyond.id), "the current task near the end");
  const missing = new TranscriptWatcher();
  assert.equal(await missing.latestPrompt("no-such-session-id"), undefined);
});

test("a prompt that straddles a chunk boundary, with multi-byte text across it, is read whole", async () => {
  const prompt = `${"é日本語".repeat(150)} ends here`;
  const target = user(prompt);
  const length = Buffer.byteLength(target);
  const overhead = Buffer.byteLength(assistant(""));
  const filler = (bytes: number) => assistant("f".repeat(bytes - overhead));
  const expected = prompt.slice(0, 200);
  const chunk = 256 * 1024;
  for (let behind = chunk - length + 1; behind < chunk; behind += 13) {
    const t = transcript("straddle", target + filler(behind));
    const boundary = Buffer.byteLength(target) + behind - chunk;
    assert.ok(boundary > 0 && boundary < length, `behind ${behind} puts the chunk boundary ${boundary} bytes into the prompt`);
    assert.equal(await t.watcher.latestPrompt(t.id), expected, `boundary ${boundary}`);
  }
});

test("cross-session messages and reminders are removed wherever they sit, and what is left is the prompt", () => {
  assert.equal(latestUserPrompt(user('FYI\n<cross-session-message from="x">hi PEER</cross-session-message>')), "FYI");
  assert.equal(latestUserPrompt(user('<cross-session-message from="uds:/x" from-name="a">do it</cross-session-message>\nfix the build <system-reminder>noise</system-reminder> please')), "fix the build please");
  assert.equal(latestUserPrompt(user("real one") + user('<cross-session-message from="x">only a peer</cross-session-message>')), "real one");
  assert.equal(latestUserPrompt(user("real one") + user('<cross-session-message from="x">a</cross-session-message><system-reminder>b</system-reminder>')), "real one");
  assert.equal(latestUserPrompt(user("keep <cross-session-messages> as text and <system-reminders> too")), "keep <cross-session-messages> as text and <system-reminders> too");
});

test("a long run of closed reminders never leaves a cut tag behind", () => {
  const reminders = "<system-reminder>a</system-reminder>".repeat(6000);
  assert.equal(latestUserPrompt(user(`${reminders}real prompt after reminders`)), "real prompt after reminders");
  assert.equal(latestUserPrompt(user(`${reminders}${reminders}${reminders}`)), undefined);
  const peers = '<cross-session-message from="x">m</cross-session-message>'.repeat(4000);
  assert.equal(latestUserPrompt(user(`before ${peers} after`)), "before after");
});

test("only regular files are read: a symlinked or FIFO transcript is ignored without blocking", async () => {
  const outside = join(root, "outside-secret.jsonl");
  writeFileSync(outside, user("OUTSIDE FILE CONTENT via symlink"));
  const linked = transcript("link", "");
  rmSync(linked.path);
  symlinkSync(outside, linked.path);
  assert.equal(linked.watcher.locate(linked.id), undefined);
  assert.equal(await linked.watcher.latestPrompt(linked.id), undefined);
  assert.deepEqual(await linked.watcher.scan(linked.id, new Set(["m1"])), []);

  const piped = transcript("fifo", "");
  rmSync(piped.path);
  execFileSync("mkfifo", [piped.path]);
  const outcome = await Promise.race([piped.watcher.latestPrompt(piped.id).then((p) => `resolved ${String(p)}`), new Promise<string>((r) => setTimeout(() => r("BLOCKED"), 2000))]);
  assert.equal(outcome, "resolved undefined");
});

test("a file swapped for a FIFO or a link after it was located is refused when opened, never waited on", async () => {
  const swapped = transcript("swap", user("fine"));
  rmSync(swapped.path);
  execFileSync("mkfifo", [swapped.path]);
  const verdict = await Promise.race([openRegularFile(swapped.path).then(() => "OPENED", (e: Error) => e.message), new Promise<string>((r) => setTimeout(() => r("BLOCKED"), 2000))]);
  assert.match(verdict, /not a regular file/);
  const target = join(root, "swap-target.jsonl");
  writeFileSync(target, "{}\n");
  const link = join(dirname(swapped.path), "swap-link.jsonl");
  symlinkSync(target, link);
  await assert.rejects(openRegularFile(link), /ELOOP|symbolic link/);
});

test("the result is cached per file by size and mtime, so an unchanged transcript is not parsed again", async () => {
  const t = transcript("cache", user("first prompt"));
  utimesSync(t.path, 1_700_000_000, 1_700_000_000);
  assert.equal(await t.watcher.latestPrompt(t.id), "first prompt");
  const before = statSync(t.path);
  writeFileSync(t.path, user("other prompt"));
  utimesSync(t.path, 1_700_000_000, 1_700_000_000);
  assert.deepEqual([statSync(t.path).size, statSync(t.path).mtimeMs], [before.size, before.mtimeMs], "same size, same mtime");
  assert.equal(await t.watcher.latestPrompt(t.id), "first prompt", "served from the cache");
  appendFileSync(t.path, user("a newer prompt that changes the size"));
  assert.equal(await t.watcher.latestPrompt(t.id), "a newer prompt that changes the size");
});
